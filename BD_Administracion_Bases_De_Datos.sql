--1: Una vez que un usuario cambie de activo a inactivo se borran todos sus permisos y roles
create or replace procedure p_cambioEstado(p_idUsuario NUMBER) 
is
  v_tienePermiso number;
  v_tieneRoles number;

begin
  -- Eliminar permisos directos
  v_tienePermiso:= f_tienePermisos(p_idUsuario);
  if v_tienePermiso = 1 then
      delete from permisosUsuarios
      where idUsuario = p_idUsuario;
   end if;

  -- Eliminar roles
  v_tieneRoles:=f_tieneRoles(p_idUsuario);
  if v_tieneRoles = 1 then
      delete from usuariosRoles
      where idUsuario = p_idUsuario;
    end if;
  
end;
-- 2: Se encarga de por medio del id usuario devolver la vista con los permisos y pantallas que tiene acceso*********************************
--out sys_refcursor es una tabla dinamica en memoria que el procedimiento va a llenar
create or replace procedure p_permisosUsuario ( p_idusuario number, p_resultado out sys_refcursor)
is
begin
    open p_resultado for
        select *
        from v_permisos_usuario
        where idusuario = p_idusuario;
end;

-- 3: Se encarga de eliminar los permisos de un rol en todas las pantallas de un sistema
create or replace procedure P_EliminarPermisosPorRol(
    v_idrol in number,
    v_idsistema in number) is
begin
    delete from permisosroles
    where idrol = p_idrol
    and idpantalla in (
        select idpantalla
        from pantallas
        where idsistema = v_idsistema
    );
    delete from UsuariosRoles
    where idrol = v_idrol
    ;
end;

-- 4:procedimiento para eliminar permisos relacionados a una pantalla
create or replace procedure P_EliminarPermisosPorPantalla(
    v_idPantalla in number,
    v_idSistema in number
) is
begin
    delete from permisosRoles
    where idPantalla = v_idPantalla
    and idSistema = v_idSistema;

    delete from permisosUsuarios
    where idPantalla = v_idPantalla
    and idSistema = v_idSistema;
end;

-- 5: otorgar permisos al rol administrador en todas las pantallas del sistema de seguridad
-- si no existen los permisos, los crea, si ya existen los actualiza
create or replace procedure p_OtorgarPermisosRol(
    v_idRol in number,
    v_idSistema in number
) is
    cursor c_permisos is
        select idpantalla
        from pantallas
        where idSistema = v_idSistema;
    v_cantidad number := 0;
begin
    for i in c_permisos loop
        select count(*) into v_cantidad 
        from permisosRoles
        where idRol = v_idRol and idSistema = v_idSistema and idPantalla = i.idPantalla;

        if v_cantidad = 0 then
            insert into permisosRoles (idRol, idPantalla, idSistema, permisoInsertar, permisoModificar, permisoBorrar, permisoConsultar)
            values (v_idRol, i.idPantalla, v_idSistema, 1, 1, 1, 1);
        else
            update permisosRoles
            set permisoInsertar = 1,
                permisoModificar = 1,
                permisoBorrar = 1,
                permisoConsultar = 1
            where idRol = v_idRol and idSistema = v_idSistema and idPantalla = i.idPantalla; 
        end if;
    end loop;
end;


-- 6: inicia el procedimiento para crear o actualizar  el rol de administrador y otorgar permisos en las pantallas del sistema de seguridad uno
create or replace procedure p_CreacionRoleAdministrador(idSistema IN NUMBER,idAdmin in number)
IS
    v_idSistema NUMBER := idSistema;
    v_idRol NUMBER := 0;
    v_countroleAdmin number :=0;
BEGIN
    v_idRol := F_ObtenerIdRolAdministrador(v_idsistema);
    p_OtorgarPermisosRol(v_idRol, v_idSistema);
    select count(*)into v_countroleAdmin from UsuariosRoles where idrol=v_idrol and idusuario=idAdmin;
    if v_countroleAdmin = 0 then
        insert into  UsuariosRoles values (idAdmin,v_idrol); 
    end if;
END;

--7: procedure que da los permisos en las pantallas del sistema de seguridad  
create or replace procedure p_DarPermisosPantallaSeguridad (v_idAdmin IN NUMBER, v_idSistema IN NUMBER) IS
    cursor c_permisos is
        select idpantalla
        from pantallas
        where idSistema = v_idSistema;
        v_cantidad NUMBER:=0;
BEGIN
    for i in c_permisos loop
        select count(*) into v_cantidad from permisosUsuarios pu join usuarios u on pu.idUsuario = u.idUsuario 
        where u.correo = 'AdminSeguridad@Gmail.com' 
        and pu.idSistema = v_idSistema and pu.idPantalla = i.idPantalla
        and pu.idpantalla = i.idPantalla;
    IF v_cantidad = 0 THEN
        INSERT INTO permisosUsuarios (idUsuario, idPantalla, idSistema, permisoInsertar, permisoModificar, permisoBorrar, permisoConsultar)
        VALUES (v_idAdmin, i.idPantalla, v_idSistema, 1, 1, 1, 1);
    ELSE
        update permisosUsuarios
        set permisoInsertar = 1,
            permisoModificar = 1,
            permisoBorrar = 1,
            permisoConsultar = 1
        where idUsuario = v_idAdmin and idSistema = v_idSistema and idPantalla = i.idPantalla; 
    END IF;
        
    end loop;
END;


-- 8: procedure que verifica si la tabla de usuarios no posee ningún dato (cuando esten todos los usuarios inavilitados)
-- se crea o actualiza un administrador por defecto. Es para que la tabla nunca quede sin administrador,

