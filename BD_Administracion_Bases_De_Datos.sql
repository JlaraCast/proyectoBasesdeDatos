--4: Es un trigger que se ejecuta antes de eliminar una pantalla, y elimina los permisos asociados a esa pantalla en todos los roles,

create or replace trigger t_EliminarPermisosPantalla
before delete on pantallas
for each row
begin
    p_EliminarPermisosPorPantalla(:old.idPantalla, :old.idSistema);
end;

-- 5:trigger para crear un rol administrador si no existe el rol de administrador en cada sistema
create or replace trigger t_crearroleadministrador
after delete on roles
declare
    v_idsistema number;
    v_cantidadroles number;
begin
    -- por cada sistema existente en la tabla sistemas
    for i in (select idsistema from sistemas) loop
        
        -- contar roles para ese sistema
        select count(*) into v_cantidadroles
        from roles
        where idsistema = i.idsistema;
        
        -- si para ese sistema no quedó ningún rol
        if v_cantidadroles = 0 then
            -- crear el rol administrador para ese sistema
            p_creacionroleadministradorsinasignar(i.idsistema);
        end if;
    end loop;
end;


