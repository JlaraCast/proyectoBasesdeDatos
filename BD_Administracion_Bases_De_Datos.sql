--1: Verifica si un usuario tiene permisos
create or replace function f_tienePermisos(p_idUsuario number)
return number
is
  v_total number;
begin
  select count(*) into v_total
  from permisosusuarios
  where idusuario = p_idUsuario;

  if v_total > 0 then
    return 1;
  else
    return 0;
  end if;
end;

--2: Verifica si un usuario tiene roles
create or replace function f_tieneRoles(p_idUsuario number)
return number
is
  v_total number;
begin
  select count(*) into v_total
  from usuariosRoles
  where idusuario = p_idUsuario;

  if v_total > 0 then
    return 1;
  else
    return 0;
  end if;
end;

--3: funcion para obtener el id del rol administrador, si no existe lo crea
-- si existe lo retorna
create or replace function f_obteneridroladministrador(p_idSistema in number)
return number is
    v_idrol number;
    v_cantidadroles number;
begin
    -- Crear el rol de administrador si no existe
    select count(*) into v_cantidadroles from roles
    where nombre = 'Administrador' and idSistema = p_idSistema;

    if v_cantidadroles = 0 then
        insert into roles (nombre, descripcion, idSistema)
        values ('Administrador', 'Rol de Administrador ', p_idSistema);
        
        select idRol into v_idrol from roles
        where nombre = 'Administrador' and idSistema = p_idSistema;
        
        return v_idrol;
    else
        select idRol into v_idrol from roles
        where nombre = 'Administrador' and idSistema = p_idSistema;
        
        return v_idrol;
    end if;
end;

--4: verifica que exista el administrador por defecto, si no existe devuelve 0, si existe devuelve 1
create or replace function f_ExisteAdminDefault
return number is
    v_count number := 0;
    v_activo number := 0;
begin
    select count(*) into v_count
    from usuarios
    where correo = 'AdminSeguridad@Gmail.com';

    if v_count > 0 then
        select count(*) into v_activo from usuarios where estado = 'Activo';
        if v_activo > 0 then
            return 2;
        else
            return 1;
        end if;
    else
        return 0;
    end if;
end;

---------------------------------------------------------Triggers---------------------------------------------------------------------------------

--1: Cuando se edite se comprueba si el nuevo valor es inactivo, si es asi se llama al procedimiento para eliminar sus roles y permisos
create or replace trigger t_usuarioInactivo
after update on usuarios
for each row
begin
  if :old.estado = 'Activo' and :new.estado = 'Inactivo' then
    p_cambioEstado(:new.idusuario);
  end if;
end;

-- 2: trigger que se ejecuta despues de actualizar un usuario, y verifica si el admin existe,
create trigger t_VerificacionUsuarioAdmin
after update on usuarios
begin
    p_CrearAdminDefault;
end;

--3: Es un trigger que se ejecuta antes de eliminar un rol, y elimina los permisos asociados a ese rol en todas las pantallas de un sistema,
-- aparte de su asignacion de usuarios.
create or replace trigger t_eliminarpermisosrol
