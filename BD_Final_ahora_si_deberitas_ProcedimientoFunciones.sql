idRol number generated BY DEFAULT ON NULL AS IDENTITY (START WITH 1) primary key ,
idSistema number,
nombre varchar(100) ,
descripcion varchar(255), 
foreign key (idSistema) references sistemas(idSistema)) ;


create table pantallas (
idPantalla number generated BY DEFAULT ON NULL AS IDENTITY (START WITH 1) ,
